#define RCC_BASE_ADDR        0x40023800U
#define AHB1ENR              (*(volatile uint32_t *)(RCC_BASE_ADDR + 0x30U))
#define APB2ENR              (*(volatile uint32_t *)(RCC_BASE_ADDR + 0x44U))

#define GPIOA_BASE_ADDR      0x40020000U
#define GPIOA_MODER          (*(volatile uint32_t *)(GPIOA_BASE_ADDR + 0x00U))
#define GPIOA_AFRL           (*(volatile uint32_t *)(GPIOA_BASE_ADDR + 0x20U))

#define GPIOD_BASE_ADDR      0x40020C00U
#define GPIOD_MODER          (*(volatile uint32_t *)(GPIOD_BASE_ADDR + 0x00U))
#define GPIOD_ODR            (*(volatile uint32_t *)(GPIOD_BASE_ADDR + 0x14U))

#define GPIOF_BASE_ADDR      0x40021400U
#define GPIOF_MODER          (*(volatile uint32_t *)(GPIOF_BASE_ADDR + 0x00U))
#define GPIOF_ODR            (*(volatile uint32_t *)(GPIOF_BASE_ADDR + 0x14U))

#define SPI1_BASE_ADDR       0x40013000U
#define SPI1_CR1             (*(volatile uint32_t *)(SPI1_BASE_ADDR + 0x00U))
#define SPI1_CR2             (*(volatile uint32_t *)(SPI1_BASE_ADDR + 0x04U))
#define SPI1_SR              (*(volatile uint32_t *)(SPI1_BASE_ADDR + 0x08U))
#define SPI1_DR              (*(volatile uint32_t *)(SPI1_BASE_ADDR + 0x0CU))

#define CS_LOW()             (GPIOD_ODR &= ~(1U << 14)) // PD14 (Arduino D10)
#define CS_HIGH()            (GPIOD_ODR |= (1U << 14))

#define DC_COMMAND()         (GPIOD_ODR &= ~(1U << 15)) // PD15 (Arduino D9)
#define DC_DATA()            (GPIOD_ODR |= (1U << 15))

#define RESET_LOW()          (GPIOF_ODR &= ~(1U << 12)) // PF12
#define RESET_HIGH()         (GPIOF_ODR |= (1U << 12))

